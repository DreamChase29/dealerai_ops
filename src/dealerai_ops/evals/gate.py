"""AI regression release gate for deterministic evaluation reports."""

import argparse
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from dealerai_ops.evals.schemas import (
    EvalCategory,
    EvaluationResult,
    EvaluationRunReport,
    ScoreResult,
)

DEFAULT_RESULTS_PATH = Path("evaluation/results/latest.json")
DEFAULT_THRESHOLDS_PATH = Path("evaluation/quality_thresholds.json")
DEFAULT_MARKDOWN_OUTPUT_PATH = Path("evaluation/results/quality_gate.md")
DEFAULT_JSON_OUTPUT_PATH = Path("evaluation/results/quality_gate.json")


class QualityThresholdConfig(BaseModel):
    """Version-controlled release gate threshold configuration."""

    model_config = ConfigDict(extra="forbid")

    version: str
    description: str
    minimums: dict[str, float] = Field(default_factory=dict)
    maximums: dict[str, float] = Field(default_factory=dict)


class GateMetric(BaseModel):
    """One release gate metric compared against a configured threshold."""

    model_config = ConfigDict(extra="forbid")

    name: str
    description: str
    value: float
    threshold: float
    comparator: Literal[">=", "<="]
    passed: bool
    numerator: int
    denominator: int


class QualityGateReport(BaseModel):
    """Complete release gate decision and metric details."""

    model_config = ConfigDict(extra="forbid")

    generated_at: str
    accepted: bool
    threshold_version: str
    results_path: str
    metrics: list[GateMetric]


def evaluate_gate(
    evaluation_report: EvaluationRunReport,
    config: QualityThresholdConfig,
    results_path: Path = DEFAULT_RESULTS_PATH,
) -> QualityGateReport:
    """Evaluate release metrics against configured thresholds."""
    metrics = _release_metrics(evaluation_report, config)
    return QualityGateReport(
        generated_at=datetime.now(UTC).isoformat(),
        accepted=all(metric.passed for metric in metrics),
        threshold_version=config.version,
        results_path=str(results_path),
        metrics=metrics,
    )


def load_threshold_config(path: Path = DEFAULT_THRESHOLDS_PATH) -> QualityThresholdConfig:
    """Load the version-controlled release gate threshold configuration."""
    return QualityThresholdConfig.model_validate_json(path.read_text(encoding="utf-8"))


def load_evaluation_report(path: Path = DEFAULT_RESULTS_PATH) -> EvaluationRunReport:
    """Load a deterministic evaluation report generated by ``evaluation.run``."""
    return EvaluationRunReport.model_validate_json(path.read_text(encoding="utf-8"))


def write_gate_report(
    report: QualityGateReport,
    markdown_path: Path = DEFAULT_MARKDOWN_OUTPUT_PATH,
    json_path: Path = DEFAULT_JSON_OUTPUT_PATH,
) -> None:
    """Write human-readable and machine-readable quality gate reports."""
    markdown_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    markdown_path.write_text(_markdown_report(report), encoding="utf-8")
    json_path.write_text(report.model_dump_json(indent=2), encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entrypoint for ``python -m evaluation.gate``."""
    parser = argparse.ArgumentParser(description="Run DealerAI Ops AI regression gate.")
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS_PATH)
    parser.add_argument("--config", type=Path, default=DEFAULT_THRESHOLDS_PATH)
    parser.add_argument("--markdown-output", type=Path, default=DEFAULT_MARKDOWN_OUTPUT_PATH)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT_PATH)
    args = parser.parse_args(argv)

    config = load_threshold_config(args.config)
    evaluation_report = load_evaluation_report(args.results)
    gate_report = evaluate_gate(evaluation_report, config, results_path=args.results)
    write_gate_report(
        gate_report,
        markdown_path=args.markdown_output,
        json_path=args.json_output,
    )
    _print_gate_summary(gate_report)
    return 0 if gate_report.accepted else 1


def _release_metrics(
    report: EvaluationRunReport,
    config: QualityThresholdConfig,
) -> list[GateMetric]:
    metric_values = {
        "task_success": _score_rate(report.results, "task_success"),
        "tool_selection_accuracy": _score_rate(
            report.results,
            "expected_tool_called",
            category=EvalCategory.TOOL_SELECTION,
        ),
        "transaction_consistency": _score_rate(
            report.results,
            "transaction_state_consistency",
            exclude_not_applicable=True,
        ),
        "pii_safety_pass_rate": _scenario_pass_rate(
            report.results,
            category=EvalCategory.PII_SAFETY,
        ),
        "required_escalation_recall": _score_rate(
            report.results,
            "required_escalation",
            exclude_not_applicable=True,
        ),
        "rag_retrieval_hit_rate": _score_rate(
            report.results,
            "retrieval_hit",
            category=EvalCategory.RAG,
            exclude_not_applicable=True,
        ),
        "hallucinated_transaction_rate": _score_failure_rate(
            report.results,
            "hallucinated_transaction",
            exclude_not_applicable=True,
        ),
    }
    descriptions = {
        "task_success": "Pass rate for the task_success scorer across all scenarios.",
        "tool_selection_accuracy": (
            "Pass rate for expected tool calls in tool-selection scenarios."
        ),
        "transaction_consistency": (
            "Pass rate for applicable transaction_state_consistency scorer results."
        ),
        "pii_safety_pass_rate": "Scenario pass rate for PII/safety scenarios.",
        "required_escalation_recall": (
            "Pass rate for applicable required_escalation scorer results."
        ),
        "rag_retrieval_hit_rate": "Pass rate for RAG retrieval_hit scorer results.",
        "hallucinated_transaction_rate": (
            "Failure rate for applicable hallucinated_transaction scorer results."
        ),
    }

    metrics: list[GateMetric] = []
    for name, threshold in config.minimums.items():
        value = metric_values[name]
        metrics.append(
            GateMetric(
                name=name,
                description=descriptions[name],
                value=value.value,
                threshold=threshold,
                comparator=">=",
                passed=value.value >= threshold,
                numerator=value.numerator,
                denominator=value.denominator,
            )
        )
    for name, threshold in config.maximums.items():
        value = metric_values[name]
        metrics.append(
            GateMetric(
                name=name,
                description=descriptions[name],
                value=value.value,
                threshold=threshold,
                comparator="<=",
                passed=value.value <= threshold,
                numerator=value.numerator,
                denominator=value.denominator,
            )
        )
    return metrics


class _Rate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    value: float
    numerator: int
    denominator: int


def _scenario_pass_rate(
    results: list[EvaluationResult],
    category: EvalCategory,
) -> _Rate:
    relevant = [result for result in results if result.category == category]
    numerator = sum(1 for result in relevant if result.passed)
    denominator = len(relevant)
    return _rate(numerator, denominator)


def _score_rate(
    results: list[EvaluationResult],
    score_name: str,
    category: EvalCategory | None = None,
    exclude_not_applicable: bool = False,
) -> _Rate:
    relevant_scores = _matching_scores(results, score_name, category, exclude_not_applicable)
    numerator = sum(1 for score in relevant_scores if score.passed)
    return _rate(numerator, len(relevant_scores))


def _score_failure_rate(
    results: list[EvaluationResult],
    score_name: str,
    exclude_not_applicable: bool = False,
) -> _Rate:
    relevant_scores = _matching_scores(
        results,
        score_name,
        category=None,
        exclude_not_applicable=exclude_not_applicable,
    )
    numerator = sum(1 for score in relevant_scores if not score.passed)
    return _rate(numerator, len(relevant_scores))


def _matching_scores(
    results: list[EvaluationResult],
    score_name: str,
    category: EvalCategory | None,
    exclude_not_applicable: bool,
) -> list[ScoreResult]:
    scores: list[ScoreResult] = []
    for result in results:
        if category is not None and result.category != category:
            continue
        for score in result.scores:
            if score.name != score_name:
                continue
            if exclude_not_applicable and score.details.get("not_applicable") is True:
                continue
            scores.append(score)
    return scores


def _rate(numerator: int, denominator: int) -> _Rate:
    value = numerator / denominator if denominator else 0.0
    return _Rate(value=value, numerator=numerator, denominator=denominator)


def _print_gate_summary(report: QualityGateReport) -> None:
    status = "accepted" if report.accepted else "failed"
    print(f"AI regression gate {status} using thresholds {report.threshold_version}.")
    failing = [metric for metric in report.metrics if not metric.passed]
    if not failing:
        print("All configured quality thresholds passed.")
        return
    print("Failing metrics:")
    for metric in failing:
        print(
            f"- {metric.name}: value={metric.value:.4f} "
            f"required {metric.comparator} {metric.threshold:.4f} "
            f"({metric.numerator}/{metric.denominator})"
        )


def _markdown_report(report: QualityGateReport) -> str:
    status = "ACCEPTED" if report.accepted else "FAILED"
    lines = [
        "# DealerAI Ops Quality Gate Report",
        "",
        f"Generated at: `{report.generated_at}`",
        f"Threshold version: `{report.threshold_version}`",
        f"Evaluation results: `{report.results_path}`",
        f"Release decision: **{status}**",
        "",
        "| Metric | Value | Threshold | Result | Definition |",
        "| --- | ---: | ---: | --- | --- |",
    ]
    for metric in report.metrics:
        result = "pass" if metric.passed else "fail"
        lines.append(
            f"| `{metric.name}` | {metric.value:.4f} "
            f"({metric.numerator}/{metric.denominator}) | "
            f"{metric.comparator} {metric.threshold:.4f} | {result} | "
            f"{metric.description} |"
        )
    return "\n".join(lines) + "\n"
